"""
المرحلة 2: تنضيف بسيط للمستندات المحمّلة من الـ PDF.

ملحوظة: الخطوة دي مكانتش موجودة في النسخة الأصلية من app.py (كان بيروح مباشرة من
التحميل للتقطيع). ضفتها هنا بس عشان الاسم "02_preprocessing.py" يبقى له معنى فعلي،
والتنضيف اللي بيعمله (إزالة الصفحات الفاضية تمامًا + توحيد المسافات) آمن 100%:
مش بيغيّر أي محتوى حقيقي، بس بيشيل صفحات فاضية كانت أصلاً هتتحول لـ chunks فاضية
مالهاش أي فايدة في الإجابة.
"""


def clean_documents(documents):
    """
    بتوحّد المسافات الزيادة في كل صفحة، وبتشيل الصفحات اللي محتواها فاضي تمامًا
    بعد التنضيف (زي صفحات الغلاف الفاضية أو صفحات فيها صور بس بدون نص).
    """
    cleaned = []
    for doc in documents:
        normalized_text = " ".join(doc.page_content.split())
        if normalized_text.strip():
            doc.page_content = normalized_text
            cleaned.append(doc)
    return cleaned
